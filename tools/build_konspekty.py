#!/usr/bin/env python3
"""Собирает конспекты/РNN_*.md из build/pages/стрNNN.txt (полный текст раздела с метками страниц).

Ручная часть (шапка «Ключевое» и пр.) хранится в конспекты/_шапки/РNN.md и вставляется в начало.
Запуск: python3 tools/extract_text.py && python3 tools/build_konspekty.py
"""
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
PAGES = ROOT / "build" / "pages"
OUT = ROOT / "конспекты"
HEAD = OUT / "_шапки"
FIG = ROOT / "рисунки"

# (код, первая стр. PDF, последняя стр. PDF, название)
SECTIONS = [
    ("Р00", 1, 1, "Титульный_лист"),
    ("Р01", 2, 21, "Назначение_буровых_растворов"),
    ("Р02", 22, 41, "Общая_химия"),
    ("Р03", 42, 59, "Химия_поверхностного_слоя"),
    ("Р04", 60, 107, "Минералогия_глин_и_коллоидная_химия"),
    ("Р05", 108, 185, "Определение_параметров_бурового_раствора"),
    ("Р06", 186, 245, "Компоненты_буровых_растворов"),
    ("Р07", 246, 285, "Фильтрационные_свойства"),
    ("Р08", 286, 341, "Устойчивость_ствола_скважины"),
    ("Р09", 342, 361, "Поглощения"),
    ("Р10", 362, 375, "Прихваты_инструмента"),
    ("Р11", 376, 397, "Коррозия"),
    ("Р12", 398, 425, "Заканчивание_скважин"),
    ("Р13", 426, 451, "Очистка_от_выбуренной_породы"),
    ("Р14", 452, 493, "Инженерные_расчеты"),
    ("Р15", 494, 521, "Реология_и_гидравлика"),
    ("Р16", 522, 543, "Охрана_окружающей_среды"),
]

def main():
    OUT.mkdir(exist_ok=True)
    for code, a, b, name in SECTIONS:
        title = name.replace("_", " ")
        parts = []
        h = HEAD / f"{code}.md"
        if h.exists():
            parts.append(h.read_text(encoding="utf-8").rstrip() + "\n\n---\n")
        else:
            parts.append(f"# {code}. {title}\n\n**Источник:** конспект лекций, стр. PDF {a}–{b} "
                         f"(печатная стр. = PDF + 4).\n\n---\n")
        parts.append(f"## Полный текст раздела (дословно, текстовый слой PDF)\n\n"
                     f"Метка `<!-- стр. N -->` = страница PDF. Формулы и таблицы текстовый слой может портить — "
                     f"сверять с рисунком страницы `рисунки/{code}/стрNNN.jpg`.\n")
        for i in range(a, b + 1):
            txt = (PAGES / f"стр{i:03d}.txt").read_text(encoding="utf-8").rstrip()
            fig = FIG / code / f"стр{i:03d}.jpg"
            figline = f"\n🖼 рисунок страницы: `рисунки/{code}/стр{i:03d}.jpg`\n" if fig.exists() else ""
            parts.append(f"\n<!-- стр. {i} -->\n### стр. {i} (печ. {i+4})\n{figline}\n```text\n{txt}\n```\n")
        (OUT / f"{code}_{name}.md").write_text("\n".join(parts), encoding="utf-8")
    print("ok")

if __name__ == "__main__":
    main()
